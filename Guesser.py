import random

# сгенерует случайное число
r = random.randint(1,10)

# сказать пользователю что было загадано число
# взять его ответ и сказать угадал он или нет
# использовать if-else
print("Выберите число от 1 до 10!)")
x = int(input())
if x == r:
    print("Вы угадали число!^_^")
else:
    print("Вы не угадали! :(")
    print(f"Загаданное число было {r}")
