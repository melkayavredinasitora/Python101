temperatures = [29.0, 25.0, 26.5, 23.0, 24.8, 29.9, 31.0, 28.2, 22.3, 21.1, 25.1, 21.4, 23.0, 27.2]

# Даны наблюдения по температуре воздуха за определенный период времени
# Нужно найти среднюю температуру за этот период и вывести её на экран
# len()

sum = 0
for t in temperatures:
    sum += t  # sum = sum + t

avg = sum / len(temperatures)
print(avg)
